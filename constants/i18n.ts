export type TranslationDictionary = typeof idDict;

export const TRANSLATIONS: Record<AppLanguage, TranslationDictionary> = {
  id: idDict,
  en: enDict,
};

export function getTranslations(lang: AppLanguage = activeLanguage): TranslationDictionary {
  return TRANSLATIONS[lang] ?? TRANSLATIONS.id;
}

export function getActivityLabel(
  type: WorkoutType,
  t: TranslationDictionary,
  uppercase: boolean = false
): string {
  if (uppercase) {
    if (type === 'walk') return t.activityTypes.walkUpper;
    if (type === 'jog') return t.activityTypes.jogUpper;
    return t.activityTypes.runUpper;
  }
  if (type === 'walk') return t.activityTypes.walk;
  if (type === 'jog') return t.activityTypes.jog;
  return t.activityTypes.run;
}

